#!/usr/bin/env python3
"""Produce an original, unfilled scientific-article reading worksheet (RU PDF + DOCX)."""
from __future__ import annotations
from pathlib import Path
import types

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "public" / "downloads" / "research"
ENGINE = ROOT / "scripts" / "build-professional-assessment-toolkit-v2.py"

def main() -> None:
    source = ENGINE.read_text(encoding="utf-8")
    source = source.replace(
        "AUTISMHUB / РАБОЧИЙ МАТЕРИАЛ ДЛЯ СПЕЦИАЛИСТОВ",
        "AUTISMHUB / НАУЧНАЯ ГРАМОТНОСТЬ"
    ).replace(
        "AUTISMHUB / ПРОФЕССИОНАЛЬНЫЕ РАБОЧИЕ МАТЕРИАЛЫ",
        "AUTISMHUB / НАУЧНАЯ ГРАМОТНОСТЬ"
    ).replace(
        "Не валидированная диагностическая шкала. Не обязательный бланк Республики Казахстан.",
        "Авторский учебный рабочий лист. Не валидированная шкала оценки научного качества."
    )
    module = types.ModuleType("research_reading_worksheet_engine")
    module.__file__ = str(ENGINE)
    exec(compile(source, str(ENGINE), "exec"), module.__dict__)
    module.OUT = OUT
    module.DATE = "15.10.2026"
    OUT.mkdir(parents=True, exist_ok=True)
    form = {
      "filename": "scientific-article-reading",
      "title": "Читаем научную статью: рабочий лист",
      "audience": "Для родителей и всех читателей научных публикаций",
      "purpose": "Ответьте на вопросы по одной научной публикации. Ищите оригинальную работу, отличайте результаты от обещаний и формулируйте собственный осторожный вывод.",
      "sections": [
        {"title": "1. Находим оригинальную публикацию", "rows": [
          ["Название, авторы, год", "Точное название работы, журнал, дата."],
          ["Ссылка и DOI", "Откройте оригинал, а не рекламный пересказ."],
          ["Главный вопрос", "Какой ровно вопрос пытались решить авторы?"],
          ["Тип работы", "Когорта, RCT, обзор, качественное исследование или другое?"]]},
        {"title": "2. Проверяем методы", "rows": [
          ["Участники", "Сколько людей, кто, где и когда участвовал?"],
          ["Критерии отбора", "Кого не включили и почему это важно?"],
          ["Сравнение и учёт факторов", "Были ли группы, рандомизация, корректировки?"],
          ["Измеряемый результат", "Что конкретно измеряли и чем?"]]},
        {"title": "3. Читаем цифры без преувеличения", "rows": [
          ["Основная оценка", "Каков размер эффекта, ассоциация или частота?"],
          ["Неопределённость", "Какой доверительный интервал, размер выборки?"],
          ["Абсолютные числа", "Есть ли числитель, знаменатель и срок наблюдения?"],
          ["Результаты, которые не подтвердились", "Упоминаются ли нулевые и неблагоприятные исходы?"]]},
        {"title": "4. Делаем осторожный вывод", "rows": [
          ["Ограничения", "Ошибки отбора, потери участников, неизмеренные факторы?"],
          ["Применимость", "Для кого, какой страны и условий справедлив вывод?"],
          ["Интересы и повторная проверка", "Финансирование, конфликты, независимые исследования?"],
          ["Вывод своими словами", "Что работа показывает, а чего не позволяет утверждать?"]]}
      ],
      "notes": [
        "Ни одна галочка не означает автоматического подтверждения качества исследования.",
        "Не смешивайте корреляцию с причинностью и p-value с вероятностью истинности гипотезы.",
        "Если итог неясен, запишите неопределённость: это корректный результат критического чтения.",
        "Не вводите персональные сведения о детях или медицинские документы в публичные сервисы."
      ],
      "references": [
        ["STROBE: наблюдательные исследования", "https://www.equator-network.org/reporting-guidelines/strobe/"],
        ["CONSORT 2025: отчётность РКИ", "https://www.bmj.com/content/389/bmj-2024-081123"],
        ["Cochrane Handbook, Chapter 14", "https://www.cochrane.org/authors/handbooks-and-manuals/handbook/current/chapter-14"]
      ]
    }
    for file in [module.build_pdf(form), module.build_docx(form)]:
        output = OUT / file
        assert output.exists() and output.stat().st_size > 2500, file
        print("SCIENCE_WORKSHEET_BUILT", file, output.stat().st_size)

if __name__ == "__main__":
    main()
